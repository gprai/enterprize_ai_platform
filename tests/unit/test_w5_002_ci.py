def test_scan_summary_binds_image_database_and_all_severity_counts(tmp_path: Path) -> None:
    identity = tmp_path / "image-identity.json"
    w5_002_ci.write_json(identity, _image_identity())
    raw = tmp_path / "trivy.json"
    raw.write_text(
        json.dumps(
            {
                "Results": [
                    {
                        "Vulnerabilities": [
                            {"Severity": "CRITICAL"},
                            {"Severity": "HIGH"},
                            {"Severity": "MEDIUM"},
                            {"Severity": "LOW"},
                        ]
                    }
                ]
            }
        )
        + "\n",
        encoding="utf-8",
    )
    output = tmp_path / "trivy-image.json"
    w5_002_ci.write_scan_summary(
        raw,
        output,
        identity,
        "trivy",
        "oci",
        DATABASE_DIGEST,
    )
    summary = json.loads(output.read_text(encoding="utf-8"))

    assert summary["critical_vulnerabilities"] == 1
    assert summary["high_vulnerabilities"] == 1
    assert summary["medium_vulnerabilities"] == 1
    assert summary["low_vulnerabilities"] == 1
    assert summary["application_manifest_digest"] == DIGEST
    assert summary["scanner_database_identity"] == DATABASE_DIGEST


def test_sensitive_content_is_rejected_without_echoing_the_value() -> None:
    sensitive_value = "joined-" + "private-" + "material"
