def test_canonical_json_is_sorted_finite_and_has_one_final_newline() -> None:
    assert w5_002_ci.canonical_json({"z": 2, "a": 1}) == '{"a":1,"z":2}\n'
    with pytest.raises(w5_002_ci.ContractError, match="non-finite"):
        w5_002_ci.canonical_json({"value": float("nan")})


def test_strict_loader_rejects_duplicate_keys_and_bom(tmp_path: Path) -> None:
    duplicate = tmp_path / "duplicate.json"
    duplicate.write_text('{"a":1,"a":2}\n', encoding="utf-8")
    with pytest.raises(w5_002_ci.ContractError, match="duplicate"):
        w5_002_ci.load_json(duplicate)

    bom = tmp_path / "bom.json"
    bom.write_bytes(b"\xef\xbb\xbf{}\n")
    with pytest.raises(w5_002_ci.ContractError, match="BOM"):
        w5_002_ci.load_json(bom)


def test_configuration_is_canonical_python_313_and_preserves_formal_failures() -> None:
    path = ROOT / "configs/ci/w5-002.json"
    value = w5_002_ci.load_json(path)
    validated = w5_002_ci.validate_config(value)

    assert path.read_text(encoding="utf-8") == w5_002_ci.canonical_json(value)
    assert validated["schema_version"] == "w5-002.ci-config.v2"
    assert validated["python"]["version"] == "3.13.15"  # type: ignore[index]
    assert validated["historical"]["w5_002_formal_status"] == "FAIL"  # type: ignore[index]
    assert validated["w5_001"] == {"formal_status": "FAIL"}


def _write_lock(path: Path, packages: tuple[tuple[str, str], ...], *, cpu: bool) -> None:
    command = (
        "# This file was autogenerated by uv via the following command:\n"
        "# uv pip compile --generate-hashes --no-build --no-python-downloads "
        "--python-version 3.13.15 --python-platform x86_64-unknown-linux-gnu\n"
    )
    lines = [command.rstrip()]
    if cpu:
        lines.append(f"--extra-index-url {w5_002_ci.PYTORCH_INDEX_URL}")
    for name, version in packages:
        lines.extend((f"{name}=={version} \\", f"    --hash=sha256:{'a' * 64}"))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def test_dependency_locks_require_python_313_cpu_torch_and_isolated_checkov(
    tmp_path: Path,
) -> None:
    runtime = tmp_path / "requirements-runtime.lock"
    checkov = tmp_path / "requirements-checkov.lock"
    _write_lock(runtime, (("fastapi", "0.141.1"), ("torch", "2.13.0+cpu")), cpu=True)
    _write_lock(checkov, (("checkov", "3.3.16"),), cpu=False)

    assert w5_002_ci.validate_dependency_lock(runtime, "runtime")["torch"] == "2.13.0+cpu"
    assert w5_002_ci.validate_dependency_lock(checkov, "checkov") == {"checkov": "3.3.16"}


@pytest.mark.parametrize("package", ("cuda-bindings", "nvidia-cublas", "triton"))
def test_dependency_lock_rejects_every_prohibited_gpu_package(
    tmp_path: Path,
    package: str,
) -> None:
    lock = tmp_path / "requirements-runtime.lock"
    _write_lock(lock, (("torch", "2.13.0+cpu"), (package, "1.0.0")), cpu=True)

    with pytest.raises(w5_002_ci.ContractError, match="prohibited GPU package"):
        w5_002_ci.validate_dependency_lock(lock, "runtime")


def test_dependency_lock_rejects_wrong_python_torch_or_index(tmp_path: Path) -> None:
    wrong_python = tmp_path / "wrong-python.lock"
    wrong_torch = tmp_path / "wrong-torch.lock"
    missing_index = tmp_path / "missing-index.lock"
    _write_lock(wrong_python, (("torch", "2.13.0+cpu"),), cpu=True)
    wrong_python.write_text(
        wrong_python.read_text(encoding="utf-8").replace("3.13.15", "3.11.16"),
        encoding="utf-8",
    )
    _write_lock(wrong_torch, (("torch", "2.14.0+cpu"),), cpu=True)
    _write_lock(missing_index, (("torch", "2.13.0+cpu"),), cpu=False)

    with pytest.raises(w5_002_ci.ContractError, match="Python 3.13.15"):
        w5_002_ci.validate_dependency_lock(wrong_python, "runtime")
    with pytest.raises(w5_002_ci.ContractError, match="Torch 2.13 CPU"):
        w5_002_ci.validate_dependency_lock(wrong_torch, "runtime")
    with pytest.raises(w5_002_ci.ContractError, match="PyTorch CPU index"):
        w5_002_ci.validate_dependency_lock(missing_index, "runtime")


def test_dependency_lock_rejects_direct_or_unapproved_package_sources(tmp_path: Path) -> None:
    direct = tmp_path / "direct.lock"
    unapproved_index = tmp_path / "unapproved-index.lock"
    _write_lock(direct, (("torch", "2.13.0+cpu"),), cpu=True)
    direct.write_text(
        direct.read_text(encoding="utf-8").replace(
            "torch==2.13.0+cpu",
            "torch @ https://example.invalid/torch.whl",
        ),
        encoding="utf-8",
    )
    _write_lock(unapproved_index, (("torch", "2.13.0+cpu"),), cpu=True)
    unapproved_index.write_text(
        unapproved_index.read_text(encoding="utf-8")
        + "--extra-index-url https://example.invalid/simple\n",
        encoding="utf-8",
    )

    with pytest.raises(w5_002_ci.ContractError, match="direct"):
        w5_002_ci.validate_dependency_lock(direct, "runtime")
    with pytest.raises(w5_002_ci.ContractError, match="unapproved package index"):
        w5_002_ci.validate_dependency_lock(unapproved_index, "runtime")


def test_v2_schema_dispatch_binds_independent_oci_and_source_identities() -> None:
    image = w5_002_ci.validate_schema(_image_identity())
    provenance = {
        "application_manifest_digest": DIGEST,
        "image_identity_report_sha256": OTHER_DIGEST,
        "reports": [f"{name}:{OTHER_DIGEST}" for name in w5_002_ci.SUPPLY_CHAIN_NAMES[:6]],
        "scanner_databases": {"grype": DATABASE_DIGEST, "trivy": DATABASE_DIGEST},
        "schema_version": w5_002_ci.PROVENANCE_SCHEMA,
        "source_identity": _source_identity(),
        "tool_versions": w5_002_ci.EXPECTED_TOOL_VERSIONS,
    }
    rollback = {
        "application_image": image["application_image"],
        "deployment_status": "NOT RUN",
        "inputs": image["inputs"],
        "rollback_status": "IDENTITY_RECORDED",
        "schema_version": w5_002_ci.ROLLBACK_SCHEMA,
        "source_identity": _source_identity(),
    }
    eligibility = {
        "application_manifest_digest": DIGEST,
        "cleanup_retention_report_sha256": OTHER_DIGEST,
        "critical_vulnerabilities": {"grype": 0, "trivy": 0},
        "deployable": False,
        "eligible_for_owner_approval": True,
        "formal_w5_002_status": "FAIL",
        "mandatory_gates": _gates(),
        "provenance_report_sha256": OTHER_DIGEST,
        "rollback_identity_report_sha256": OTHER_DIGEST,
        "schema_version": w5_002_ci.ELIGIBILITY_SCHEMA,
        "source_identity": _source_identity(),
        "vulnerability_free_claim": False,
        "w5_001_status": "FAIL",
    }

    assert image["application_image"]["manifest_digest"] == DIGEST  # type: ignore[index]
    assert w5_002_ci.validate_schema(provenance)["schema_version"] == w5_002_ci.PROVENANCE_SCHEMA
    assert w5_002_ci.validate_schema(rollback)["rollback_status"] == "IDENTITY_RECORDED"
    assert w5_002_ci.validate_schema(_cleanup())["historical_evidence"] == "RETAINED"
    assert w5_002_ci.validate_schema(eligibility)["eligible_for_owner_approval"] is True


