def _source_identity(source_commit: str | None = None) -> dict[str, object]:
    return {
        "baseline_head": w5_002_ci.BASELINE_HEAD,
        "source_commit": source_commit,
        "source_composition_sha256": OTHER_DIGEST,
    }


